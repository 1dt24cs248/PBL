"""Generate a read-only triage report for active-term timetable conflicts."""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.timetable_import import ParsedTimetables, parse_timetables  # noqa: E402
from app.dataset import SPEC_PATH  # noqa: E402

ACTIVE_TERM = "2026-27-ODD"
OUTPUT = BACKEND_DIR.parent / "docs" / "CONFLICT_TRIAGE.md"


def _room_state(session: dict) -> str:
    if not session.get("room_id"):
        return "N/A"
    return "INFERRED" if session.get("room_inferred", False) else "EXPLICIT"


def _classify(parsed: ParsedTimetables, conflict: dict, first: dict, second: dict,
              ambiguous_initials: set[str]) -> str:
    if any(re.search(r"\bB[12]:", row["raw_label"], re.I) and row["batch"] == "ALL"
           for row in (first, second)):
        return "PARSER_SUSPECT"
    if conflict["type"] == "faculty":
        shared_initials = set(first["faculty_initials"]) & set(second["faculty_initials"])
        if shared_initials & ambiguous_initials:
            return "AMBIGUOUS_INITIALS"
    if any(_room_state(row) == "INFERRED" for row in (first, second)):
        return "INVOLVES_INFERRED_ROOM"
    return "AS_WRITTEN_BOTH_EXPLICIT"


def _source_day_line(text: str, section: str, next_section: str, day: str) -> str:
    start = re.search(rf"(?m)^5TH {section} SECTION\b", text)
    end = re.search(rf"(?m)^{re.escape(next_section)}", text[start.end():]) if start else None
    if not start:
        return "<source line unavailable>"
    body_end = start.end() + end.start() if end else len(text)
    for line in text[start.start():body_end].splitlines():
        if line.startswith(f"{day}:"):
            return line.strip()
    return "<source line unavailable>"


def build_report(parsed: ParsedTimetables) -> str:
    sessions = parsed.sessions
    faculty = [row for row in parsed.faculty if row["term_code"] == ACTIVE_TERM]
    ambiguous_initials = {
        row["initials"] for row in faculty
        if row.get("full_name") is None or row.get("provenance") == "INFERRED"
    }
    selected = [conflict for conflict in parsed.conflicts
                if conflict["term_code"] == ACTIVE_TERM
                and conflict["type"] in {"room", "faculty"}]
    counts = Counter()
    source_text = SPEC_PATH.read_text(encoding="utf-8")
    c_thursday = _source_day_line(source_text, "C", "5TH D SECTION", "Thu")
    f_thursday = _source_day_line(source_text, "F", "Dataset 2:", "Thu")
    lines = [
        "# Active-Term Conflict Triage",
        "",
        f"Scope: `{ACTIVE_TERM}` only. Generated by `backend/scripts/triage_conflicts.py` from parsed timetable data; this report does not modify timetable or source data.",
        "",
        f"Detected conflicts: {len(selected)} ({sum(c['type'] == 'room' for c in selected)} room, {sum(c['type'] == 'faculty' for c in selected)} faculty).",
        "Each row gives the overlapping period, both source labels, each parsed room and whether that room was explicit or inferred, and the triage class.",
        "",
    ]
    for conflict in selected:
        first, second = (sessions[index] for index in conflict["session_indices"])
        classification = _classify(parsed, conflict, first, second, ambiguous_initials)
        counts[classification] += 1
        lines.extend([
            f"## {conflict['type'].title()} conflict — {conflict['day']} P{conflict['period']}",
            "",
            f"Class: `{classification}`",
            f"- Section {first['section_code']} [{first['batch']}]: room `{first.get('room_id') or 'none'}` ({_room_state(first)}); raw_label: `{first['raw_label']}`",
            f"- Section {second['section_code']} [{second['batch']}]: room `{second.get('room_id') or 'none'}` ({_room_state(second)}); raw_label: `{second['raw_label']}`",
            "",
        ])
    lines.extend([
        "## Classification counts",
        "",
        " | ".join(f"`{name}`: {counts[name]}" for name in (
            "AS_WRITTEN_BOTH_EXPLICIT", "INVOLVES_INFERRED_ROOM", "AMBIGUOUS_INITIALS", "PARSER_SUSPECT"
        )),
        "",
        "## 5C / 5F Thursday P1–P2 room identity",
        "",
        "The source timetable rows are:",
        "",
        "```text",
        f"5C {c_thursday}",
        f"5F {f_thursday}",
        "```",
        "",
        "Parse path after resolver correction: the parser reads both B1/B2 branches from the 5C source row, producing parallel sessions with one `block_id`: 5C B2 `210 A` -> `A-F2-10`, and B1 `206 A` -> `A-F2-06`. The explicit 5F `A 211` label resolves to `A-F2-11`; it no longer collides with 5C B2. The prior 5C/5F room clash was caused by the erroneous F2-10 alias mapping and is removed. The source timetable row was not changed.",
        "",
        "Regression coverage asserts that `@ A 211` resolves to `A-F2-11`, the 5C parallel lab sessions retain separate rooms and a shared block ID, and the erroneous 5C/5F overlap is absent. Source data was not changed.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    report = build_report(parse_timetables())
    OUTPUT.write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
